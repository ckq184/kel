#!/usr/bin/env node
/**
 * Lifecycle helper for the self-hosted Langfuse stack used by
 * `npm run eval:auto-recall` (task Z follow-up 4, 按需起模式).
 *
 *   node scripts/eval-langfuse.mjs up      # create .env if missing, compose up -d, wait for health
 *   node scripts/eval-langfuse.mjs down    # compose down (volumes RETAINED — eval history persists)
 *   node scripts/eval-langfuse.mjs status  # compose ps + public health probe
 *
 * The Langfuse checkout location defaults to <repo>/../langfuse and can be
 * overridden with CKQCLAW_EVAL_LANGFUSE_DIR. The web UI port defaults to
 * 3300 (CKQCLAW_EVAL_LANGFUSE_PORT to change) because this machine's 3000 is
 * usually taken by dev servers — a docker-compose.eval.yml override is
 * generated next to the checkout's compose file and passed via -f. First
 * boot is interactive: open http://localhost:3300, register the admin user,
 * create an organization + project, and copy the project API keys into
 * data/config/eval-langfuse.json (or the CKQCLAW_EVAL_LANGFUSE_* env vars).
 *
 * The generated .env contains random secrets (crypto.randomBytes) with mode
 * 0o600 — this stack is for local evaluation only, not production.
 */
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const LANGFUSE_PORT = Number(process.env.CKQCLAW_EVAL_LANGFUSE_PORT ?? 3300);
const HEALTH_URL = `http://localhost:${LANGFUSE_PORT}/api/public/health`;

/** Resolve the docker CLI even when ~/.docker/bin (Docker Desktop's
 * no-sudo install location) is not on this process's PATH. */
function resolveDockerCommand() {
  for (const candidate of dockerCandidates()) {
    const probe = spawnSync(candidate, ['--version'], {
      timeout: 10_000,
      env: dockerEnv(),
    });
    if (probe.status === 0) return candidate;
  }
  return null;
}

function dockerCandidates() {
  return [
    'docker',
    path.join(os.homedir(), '.docker', 'bin', 'docker'),
    '/usr/local/bin/docker',
    '/opt/homebrew/bin/docker',
  ];
}

/** Docker Desktop keeps its credential helper (docker-credential-desktop)
 * in its Resources/bin; without it on PATH, image pulls abort with
 * "error getting credentials". Augment PATH for every docker child. */
function dockerEnv() {
  const extra = [
    path.join(os.homedir(), '.docker', 'bin'),
    '/Applications/Docker.app/Contents/Resources/bin',
  ];
  return {
    ...process.env,
    PATH: `${extra.join(':')}:${process.env.PATH ?? ''}`,
  };
}

const dockerCommand = resolveDockerCommand();

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const composeDir =
  process.env.CKQCLAW_EVAL_LANGFUSE_DIR ??
  path.join(repoRoot, '..', 'langfuse');
const composeFile = path.join(composeDir, 'docker-compose.yml');

function ensureEnvFile() {
  const envPath = path.join(composeDir, '.env');
  if (fs.existsSync(envPath)) return readEvalEnv(envPath);
  // LANGFUSE_INIT_* pre-provisions the org/project/admin AND fixed API keys,
  // so the eval flow never needs the interactive first-boot UI.
  const publicKey = `pk-lf-ckqclaw-eval-${crypto.randomBytes(8).toString('hex')}`;
  const secretKey = `sk-lf-ckqclaw-eval-${crypto.randomBytes(16).toString('hex')}`;
  const values = {
    NEXTAUTH_SECRET: crypto.randomBytes(24).toString('hex'),
    SALT: crypto.randomBytes(16).toString('hex'),
    ENCRYPTION_KEY: crypto.randomBytes(32).toString('hex'),
    NEXTAUTH_URL: `http://localhost:${LANGFUSE_PORT}`,
    LANGFUSE_S3_EVENT_UPLOAD_SECRET_ACCESS_KEY: crypto
      .randomBytes(16)
      .toString('hex'),
    LANGFUSE_S3_MEDIA_UPLOAD_SECRET_ACCESS_KEY: crypto
      .randomBytes(16)
      .toString('hex'),
    LANGFUSE_INIT_ORG_ID: 'ckqclaw-eval-org',
    LANGFUSE_INIT_ORG_NAME: 'CKQClaw Eval',
    LANGFUSE_INIT_PROJECT_ID: 'ckqclaw-eval-project',
    LANGFUSE_INIT_PROJECT_NAME: 'CKQClaw Eval',
    LANGFUSE_INIT_PROJECT_PUBLIC_KEY: publicKey,
    LANGFUSE_INIT_PROJECT_SECRET_KEY: secretKey,
    LANGFUSE_INIT_USER_EMAIL: 'admin@ckqclaw-eval.local',
    LANGFUSE_INIT_USER_NAME: 'CKQClaw Eval Admin',
    LANGFUSE_INIT_USER_PASSWORD: crypto.randomBytes(12).toString('hex'),
  };
  const env = Object.entries(values)
    .map(([key, value]) => `${key}=${value}`)
    .join('\n');
  fs.writeFileSync(envPath, `${env}\n`, { mode: 0o600 });
  process.stdout.write(`created ${envPath} with fresh random secrets\n`);
  return readEvalEnv(envPath);
}

/** Read back the eval-relevant values (URL + API keys) from the .env. */
function readEvalEnv(envPath) {
  const parsed = {};
  for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line);
    if (match) parsed[match[1]] = match[2];
  }
  return parsed;
}

function ensurePortOverride() {
  const overridePath = path.join(composeDir, 'docker-compose.eval.yml');
  const content =
    '# Generated by scripts/eval-langfuse.mjs — binds the web UI to a free\n' +
    '# port so the eval stack never fights dev servers for :3000.\n' +
    'services:\n' +
    '  langfuse-web:\n' +
    `    ports: !override ["${LANGFUSE_PORT}:3000"]\n`;
  fs.writeFileSync(overridePath, content, { mode: 0o600 });
  return overridePath;
}

function compose(args, { check = true } = {}) {
  if (!dockerCommand) {
    process.stderr.write(
      'docker CLI not found (PATH, ~/.docker/bin, /usr/local/bin, /opt/homebrew/bin)\n',
    );
    process.exitCode = 1;
    return false;
  }
  const override = ensurePortOverride();
  const result = spawnSync(
    dockerCommand,
    [
      'compose',
      '-f',
      'docker-compose.yml',
      '-f',
      path.basename(override),
      ...args,
    ],
    { cwd: composeDir, stdio: 'inherit', env: dockerEnv() },
  );
  if (check && result.status !== 0) {
    process.stderr.write(`docker compose ${args.join(' ')} failed\n`);
    process.exitCode = 1;
  }
  return result.status === 0;
}

async function waitForHealth({ timeoutMs = 180_000 } = {}) {
  const startedAt = Date.now();
  process.stdout.write(`waiting for ${HEALTH_URL} …\n`);
  for (;;) {
    try {
      const response = await fetch(HEALTH_URL);
      if (response.ok) {
        process.stdout.write(
          `langfuse healthy after ${Math.round((Date.now() - startedAt) / 1000)}s — open http://localhost:${LANGFUSE_PORT} for first-boot setup\n`,
        );
        return true;
      }
    } catch {
      /* not up yet */
    }
    if (Date.now() - startedAt > timeoutMs) {
      process.stderr.write(
        `langfuse did not become healthy within ${Math.round(timeoutMs / 1000)}s — check: docker compose -f ${composeFile} ps\n`,
      );
      process.exitCode = 1;
      return false;
    }
    await new Promise((resolve) => setTimeout(resolve, 3_000));
  }
}

function requireStack() {
  if (!fs.existsSync(composeFile)) {
    process.stderr.write(
      `docker-compose.yml not found at ${composeFile} — set CKQCLAW_EVAL_LANGFUSE_DIR to your langfuse checkout\n`,
    );
    process.exitCode = 1;
    return false;
  }
  return true;
}

async function main() {
  const command = process.argv[2];
  if (!['up', 'down', 'status'].includes(command ?? '')) {
    process.stderr.write(
      'usage: node scripts/eval-langfuse.mjs up|down|status\n',
    );
    process.exitCode = 1;
    return;
  }
  if (!requireStack()) return;

  if (command === 'up') {
    const envValues = ensureEnvFile();
    if (!compose(['up', '-d'], { check: false })) {
      process.stderr.write(
        'docker compose failed — is the docker daemon running?\n',
      );
      process.exitCode = 1;
      return;
    }
    const healthy = await waitForHealth();
    if (!healthy) return;
    // Close the config loop: hand the harness the URL + pre-provisioned API
    // keys so `npm run eval:auto-recall` works with zero manual setup.
    const publicKey = envValues['LANGFUSE_INIT_PROJECT_PUBLIC_KEY'];
    const secretKey = envValues['LANGFUSE_INIT_PROJECT_SECRET_KEY'];
    if (publicKey && secretKey) {
      const configDir = path.join(repoRoot, 'data', 'config');
      fs.mkdirSync(configDir, { recursive: true });
      const harnessConfig = path.join(configDir, 'eval-langfuse.json');
      fs.writeFileSync(
        harnessConfig,
        `${JSON.stringify(
          {
            url: `http://localhost:${LANGFUSE_PORT}`,
            publicKey,
            secretKey,
          },
          null,
          2,
        )}\n`,
        { mode: 0o600 },
      );
      process.stdout.write(`harness config written: ${harnessConfig}\n`);
    }
    return;
  }
  if (command === 'down') {
    compose(['down']);
    process.stdout.write(
      'stack stopped (volumes retained — eval history survives the next up)\n',
    );
    return;
  }
  // status
  compose(['ps'], { check: false });
  try {
    const response = await fetch(HEALTH_URL);
    process.stdout.write(
      response.ok
        ? `health: OK (${HEALTH_URL})\n`
        : `health: HTTP ${response.status}\n`,
    );
  } catch {
    process.stdout.write('health: unreachable (stack not running?)\n');
  }
}

void main();
